package com.dino.registermodule.base;

/**
 * 常用整数常量定义，集中提供代码中反复使用的固定整数值。
 */
public interface NumberConstant {

    /** 常用整数值常量集合 */
    interface Int{
        int INT_ZERO = 0;
        int INT_ONE = 1;
        int INT_TWO = 2;
        int INT_THREE = 3;
        int INT_SIX = 6;
        int INT_TEN = 10;
        int INT_TWENTY = 20;
        int INT_THOUSAND = 1000;
    }
}
